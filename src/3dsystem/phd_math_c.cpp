sint16 __fastcall phd_atan(sint32 x, sint32 y)
{
    sint32 octant, swap, angle;

    if (x == 0 && y == 0)
        return 0;
    octant = 0;
    if (x < 0) {
        octant += 4;
        x = -x;
    }
    if (y < 0) {
        octant += 2;
        y = -y;
    }
    if (y > x) {
        octant++;
        swap = x;
        x = y;
        y = swap;
    }
    angle = phdtantab[(sint32)(((__int64)(uint32)y << 11) / x)] + phdtan2[octant];
    if (angle < 0)
        angle = -angle;
    return (sint16)angle;
}

sint32 phd_sin_half_turn(sint32 angle)
{
    if (angle > 0x4000)
        angle = 0x8000 - angle;
    return phdsintab[(uint32)angle >> 4];
}

sint32 __fastcall phd_sin(sint32 angle)
{
    angle &= 0xffff;
    if (angle < 0x8000)
        return phd_sin_half_turn(angle);
    return -phd_sin_half_turn(angle - 0x8000);
}

sint32 __fastcall phd_cos(sint32 angle)
{
    return phd_sin(angle + 0x4000);
}

uint32 __fastcall phd_sqrt(uint32 n)
{
    uint32 base, root, half;

    base = 0x40000000;
    root = 0;
    do {
        half = root >> 1;
        root += base;
        if (root > n) {
            root = half;
        } else {
            n -= root;
            root = base | half;
        }
        base >>= 2;
    } while (base);
    return root;
}

